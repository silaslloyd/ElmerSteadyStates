PARAMS = """
yearinsec = 31556926.0
rhoi = 917.0e-6 / yearinsec^2              -- MPa a2 m-2
gravity = 9.81 * yearinsec^2               -- m a-2
sina = {sina}
cosa = math.sqrt(1 - sina^2)
eta = {eta}                                -- MPa a, Newtonian
Cslip = {cslip}                            -- MPa a m-1, linear sliding tau_b = C u_b
dip = {dip}                                -- fractional drop of C in the middle of the width
dipw = {dipw}                              -- its half width (m)
L = {L}
W = {W}
H = {H}
amp = {amp}                                -- surface bump (m)
rad = {rad}                                -- its radius (m)

function slip(y)
  local s = (y - W / 2) / dipw
  return Cslip * (1 - dip * math.exp(-s * s))
end

function zs0(x, y)
  local dx, dy = x - L / 2, y - W / 2
  return H + amp * math.exp(-(dx * dx + dy * dy) / (rad * rad))
end
"""

