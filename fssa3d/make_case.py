#!/usr/bin/env python3
"""Standalone 3D free-surface time-step test: full Stokes only (no heat, no ESS, no SSA shelf), stock Elmer.

A slab of ice H thick on a bed of slope sina, periodic in x and y (flowline-like: long in x, W across), driven
by gravity tilted along x. The basal friction has a dip across the width: beta(y) = C (1 - dip exp(-((y - W/2)/w)^2)),
so the ice over the middle runs faster (a stream strip with lateral shear margins). A flat surface is the exact
steady state (u = u(y, z) only), so the test is the relaxation of a Gaussian surface bump (amp, radius) back to flat,
with the surface evolved by the stock FreeSurfaceSolver and the Stokes solver stabilised by FSSA:

  --scheme explicit : Stokes, then the free surface once per step (After Timestep), the mesh mapped before the
                      next step (the usual ElmerStreams / Elmer-Ice order)
  --scheme implicit : Stokes, FreeSurface and the mesh mapping all in the coupled loop (Exec Always), iterated up
                      to --iters times a step until the Steady State tolerances are met (= ESS fs_coupled)

  --fssa full | none   (FSSA Theta 1 / 0 on the surface; "none" is unstabilised)

    python3 fssa3d/make_case.py --tag exp_full_dt10 --scheme explicit --fssa full --dt 10 --years 100 [--run]

Writes fssa3d/runs/<tag>/ (mesh, case.sif, params.lua); --run runs ElmerSolver there (serial, MUMPS).
Surface VTUs surf*.vtu (Zs, Velocity) every --out-years. Units MPa - a - m as the rest of the repo.
"""
import argparse
