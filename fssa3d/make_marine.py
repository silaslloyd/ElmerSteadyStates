"""Standalone 3D MARINE free-surface time-step test: full Stokes everywhere (grounded ice and the floating shelf),
no heat, no ESS driver, no SSA. The ESS marine grounding-line treatment is reused (ElmerStreams contact function
SlidCoef_ContactPeriodic with Periodic Contact = False, GetHydrostaticLoads, GroundedSolver, SeaPressure / SeaSpring from
elmer/Buoyancy), so build those libraries first: `bash periodic_test/run_gl_ess.cmd build` (fssa3d/run.cmd does it).

Geometry (flowline-like, 3D): x from the divide (x = 0, symmetric) to a fixed calving front at x = L; y across a
width W with free-slip walls. Bed b(x) = -b0 - slope x (deepening seaward), linear Weertman sliding with a friction
dip across the width: C(y) = C (1 - dip exp(-((y - W/2)/w)^2)) (a stream strip in the middle). Uniform accumulation
a. The start is a plain linear thickness profile H(x) crossing flotation (grounded where H >= rho_w/rho_i |b|,
Zb = -rho_i/rho_w H elsewhere): not a steady state, so ALL runs respond to the same forcing, and the question is
how the schemes follow the free-surface + grounding-line response at big steps. Reference = the smallest dt.

  --scheme explicit | implicit   (as make_case.py: implicit = Stokes, both free surfaces and the mesh mapping in the
                                   coupled loop, --iters per step)
  --fssa full | none
  --amp M   optional extra Gaussian bump on Zs (default 0)

    python3 fssa3d/make_marine.py --tag mar_exp_full_dt10 --scheme explicit --fssa full --dt 10 --years 100 [--run]

Writes fssa3d/runs/<tag>/ ; surface VTUs surf*.vtu (Zs, Velocity), base VTUs base*.vtu (Zb, GroundedMask).
Untested draft: check elmer.log of the first small-dt run before sweeping.
"""
