#!/bin/bash
# Temperate-patch sweeps at another surface temperature: for each offset in OFFSETS (K, default "1 -1") a branch of the marine
# branch BASE (default gl549s100) with Tsurf = the base's Tsurf + offset, then
#   1. gl_heat_steady.cmd: the thermal transient (steady temperature on the fixed geometry, whole bed temperate) at the new Tsurf,
#      from the base's steady_temperate.npz with --p = the new Tsurf (Tsurf is taken from the state, not the config),
#   2. gl_newton_thermal.cmd: the thermomechanical steady state at the new Tsurf, Newton from 1's thermo_heat.npz,
#   3. gl_sweep.cmd (STEP km steps, default 25, from the grounding line to 0), started when 2 has finished (afterok).
# The new branch is TAG = <BASE>_Tp<offset> or <BASE>_Tm<offset> (gl549s100_Tp1, gl549s100_Tm1): its config
# work/gl_ssa_gl<GL>/refined/branch_<TAG>.toml (the base's with the Tsurf value and its own mesh copy branchcase_<TAG>), its states in
# branch_<TAG>/ and sweep_<TAG>/. The base branch and its sweeps are not touched.
#
#   cd /SCRATCH/slloyd/github/ElmerStreams/MasterCopy/ElmerStreams/ElmerSteadyStates && DRY=1 bash jobs/gl_tsurf_sweeps.sh   # set up, print the commands
#   cd /SCRATCH/slloyd/github/ElmerStreams/MasterCopy/ElmerStreams/ElmerSteadyStates && bash jobs/gl_tsurf_sweeps.sh         # set up and submit
#   OFFSETS="1" STEP=50 bash jobs/gl_tsurf_sweeps.sh
# GL (default 549), SHELF (100), BASE (gl<GL>s<SHELF>), OFFSETS, STEP (25), SBATCH_EXTRA (more sbatch options), DRY=1 (no sbatch).
set -e
cd "$(dirname "$0")/.."
GL=${GL:-549}
SHELF=${SHELF:-100}
BASE=${BASE:-gl${GL}s${SHELF}}
STEP=${STEP:-25}
OFFSETS=${OFFSETS:-"1 -1"}
W=work/gl_ssa_gl$GL
BCFG=$W/refined/branch_$BASE.toml
BSTATE=$W/branch_$BASE/steady_temperate.npz
[ -f "$BCFG" ] || { echo "no $BCFG"; exit 1; }
[ -f "$BSTATE" ] || { echo "no $BSTATE: the base branch has no thermomechanical steady state"; exit 1; }
[ -d "$W/branchcase_$BASE" ] || { echo "no $W/branchcase_$BASE (the base branch's mesh)"; exit 1; }
T0=$(python3 -c "
import sys
sys.path.insert(0, '.')
from ess.statefile import load_state
print(round(float(load_state('$BSTATE').p), 4))")
echo "base $BASE: Tsurf $T0 K (state $BSTATE)"
for OFF in $OFFSETS; do
    if [ "${OFF#-}" != "$OFF" ]; then TAG=${BASE}_Tm${OFF#-}; else TAG=${BASE}_Tp${OFF#+}; fi
    TS=$(python3 -c "print(round($T0 + ($OFF), 4))")
    echo "== $TAG: Tsurf $TS K"
    mkdir -p $W/branch_$TAG
    if [ ! -d "$W/branchcase_$TAG" ]; then cp -r $W/branchcase_$BASE $W/branchcase_$TAG; fi
    python3 - <<PY
import sys, re
sys.path.insert(0, "jobs")
from gl_newton_gl import set_key
text = open("$BCFG").read()
text = set_key(text, "parameter", "value", "$TS")
text, n = re.subn(r"branchcase_$BASE\b", "branchcase_$TAG", text)
print(f"  config: Tsurf $TS, {n} mesh path(s) -> branchcase_$TAG")
open("$W/refined/branch_$TAG.toml", "w").write("# generated by jobs/gl_tsurf_sweeps.sh from $BCFG: Tsurf $TS K\n" + text)
PY
    HEAT="GL=$GL TAG=$TAG FROM=$BSTATE ARGS=\"--p $TS\" sbatch $SBATCH_EXTRA --job-name=glht-$TAG jobs/gl_heat_steady.cmd"
    if [ -n "$DRY" ]; then
        echo "  $HEAT"
        echo "  GL=$GL TAG=$TAG sbatch $SBATCH_EXTRA --dependency=afterok:HEATJOBID --job-name=glnt-$TAG jobs/gl_newton_thermal.cmd"
        echo "  GL=$GL TAG=$TAG STEP=$STEP sbatch $SBATCH_EXTRA --dependency=afterok:NEWTONJOBID --job-name=glsw-$TAG jobs/gl_sweep.cmd"
        continue
    fi
    HJOB=$(GL=$GL TAG=$TAG FROM=$BSTATE ARGS="--p $TS" sbatch --parsable $SBATCH_EXTRA --job-name=glht-$TAG jobs/gl_heat_steady.cmd)
    NJOB=$(GL=$GL TAG=$TAG sbatch --parsable $SBATCH_EXTRA --dependency=afterok:$HJOB --job-name=glnt-$TAG jobs/gl_newton_thermal.cmd)
    SJOB=$(GL=$GL TAG=$TAG STEP=$STEP sbatch --parsable $SBATCH_EXTRA --dependency=afterok:$NJOB --job-name=glsw-$TAG jobs/gl_sweep.cmd)
    echo "  heat job $HJOB, Newton job $NJOB, sweep job $SJOB (${STEP} km steps): work/gl_ssa_gl$GL/sweep_$TAG/"
done
