#!/usr/bin/env python3
"""ssa_start_gl_cfg.py

The config of jobs/ssa_start_gl.cmd: configs/flowline_gl_fine_ssa.toml (the SSA start, grounding line 585.57 km) with its own
work directory, its own initial-state tables and the 250 m band of the first mesh moved with the imposed grounding line.
Nothing of the original is touched.

    python3 jobs/ssa_start_gl_cfg.py --gl-km 549 --out configs/flowline_gl_fine_ssa_gl549.toml

The mesh points other than the first and the last (the calving front) are shifted by (gl_km - 585.57) km, so the band and the
graded shelf keep their place relative to the grounding line; the work dir is work/gl_ssa_gl<km> and the tables
case/marine_ics_ssa_gl<km>.
"""
import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GL0 = 585.57                                # km, the grounding line the base config's mesh was built for


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gl-km", type=float, required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--base", default=os.path.join(ROOT, "configs", "flowline_gl_fine_ssa.toml"))
    a = ap.parse_args()
    tag = f"{a.gl_km:g}"
    text = open(a.base).read()

    m = re.search(r"^res_points\s*=\s*(\[\[.*\]\])", text, re.M)
    if not m:
        raise SystemExit(f"no res_points in {a.base}")
    pts = eval(m.group(1))
    d = a.gl_km - GL0
    new = [pts[0]] + [[round(x + d, 2), res] for x, res in pts[1:-1]] + [pts[-1]]
    xs = [p[0] for p in new]
    if any(b <= c for c, b in zip(xs[:-1], xs[1:])):
        raise SystemExit(f"the shifted mesh points are not increasing: {xs}")
    eol = text.index("\n", m.end(1))                    # the base line's trailing comment describes its own band: replaced
    text = (text[:m.start(1)] + str(new) + f"   # 250 m band moved with the imposed grounding line ({a.gl_km:g} km)" + text[eol:])
    text = re.sub(r'^work_dir\s*=.*$', f'work_dir = "work/gl_ssa_gl{tag}"', text, count=1, flags=re.M)
    text = re.sub(r'^marine_ics\s*=.*$', f'marine_ics = "case/marine_ics_ssa_gl{tag}"', text, count=1, flags=re.M)
    head = (f"# GENERATED by jobs/ssa_start_gl_cfg.py: {os.path.basename(a.base)} with the grounding line imposed at {a.gl_km:g} km "
            f"(mesh band shifted by {d:+.2f} km, own work dir and tables).\n")
    open(a.out, "w").write(head + text)
    print(f"{a.out}: work_dir work/gl_ssa_gl{tag}, tables case/marine_ics_ssa_gl{tag}, res_points {new}")


if __name__ == "__main__":
    main()
