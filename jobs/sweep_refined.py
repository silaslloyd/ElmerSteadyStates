#!/usr/bin/env python3
"""The marine bed sweep (ess sweep) with the mesh refined at the cold/temperate margin: the patch head moves
downstream as d shrinks, so the sweep runs in SEGMENTS, each on its own mesh with a fine band around the heads it covers.

Segment k starts from the last converged state (of the previous segment, or of a coarse sweep), at its length d0 and
head h0 = x_gl - d0, and covers the lengths d0 .. d0 - SPAN (heads h0 .. h0 + SPAN). Its mesh is the base config's
res_points with the element size min(base, band), the band FINE m over [h0 - PAD, h0 + SPAN + PAD] graded linearly back
to the base size over GRADE on each side. For each segment:

    1. config  <work>/refined/m<h0 in km>.toml: the base config, [case] res_points the banded ones,
               [paths] case_dir "{work}/m<h0>" (the runs and the cache stay in the base work dir)
    2. ess setup, ess init, ess transfer --from the last converged state, jobs/shelf_break.py (the bed as the base
       pipeline's, jobs/flowline_coarse_newton.cmd: transfer keeps the target's own bed)
    3. ess sweep --d-start-km d0 --d-end-km d0 - SPAN on it (d0 itself solved again first: the transferred state
       converged on the refined mesh), out <work>/sweep_refined/seg_<h0>/ (sweep.csv, points/)

The next segment starts from this one's last converged point. A segment whose sweep stopped before its end (Newton
failed at the smallest step) ends the run. Rerunning resumes: finished segments are skipped, an unfinished one resumed
(ess sweep resumes after its last converged row), steps already done (config, mesh, start states) not redone.

    python3 jobs/sweep_refined.py CONFIG --from-sweep DIR | --from-state STATE.npz --d-km D
                                  [--d-end-km 0] [--span-km 50] [--pad-km 10] [--grade-km 10] [--fine 250]
                                  [--step-frac 0.2] [--step-min-km 1] [--step-max-km 25] [--gl-rounds 6] [--maxit N]
                                  [--predictor none|secant] [--dry-run]

--from-sweep: the last converged row of DIR/sweep.csv (a coarse sweep's folder, e.g.
work/flowline_rect_coarse/sweep_p268.15_down) and its state. --dry-run: the segments' meshes only (res_points printed,
nothing run).
"""
import argparse
import csv
import os
import re
import subprocess
import sys
import time

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from ess.config import load_config  # noqa: E402
from ess.spectrum import gl_position  # noqa: E402
from ess.statefile import load_state  # noqa: E402


def log(msg):
    print(f"{time.strftime('%H:%M:%S')} refined: {msg}", flush=True)


def run(cmd):
    log("$ " + " ".join(cmd))
    subprocess.run(cmd, cwd=ROOT, check=True)


def banded_points(base, a, b, fine, grade, front_km):
    """res_points (km, m) with the size min(base, band): the band `fine` over [a, b] km, graded linearly to the base
    size over `grade` km each side"""
    bx = np.array([p[0] for p in base], float)
    bh = np.array([p[1] for p in base], float)
    base_h = lambda x: float(np.interp(x, bx, bh))
    a0, b1 = max(a - grade, 0.0), min(b + grade, front_km)

    def band(x):
        if a <= x <= b:
            return fine
        if a0 < x < a:
            return fine + (base_h(a0) - fine) * (a - x) / (a - a0)
        if b < x < b1:
            return fine + (base_h(b1) - fine) * (x - b) / (b1 - b)
        return np.inf
    xs = sorted(set([float(v) for v in bx] + [a0, max(a, 0.0), min(b, front_km), b1]))
    pts = []
    for x in xs:
        h = min(base_h(x), band(x))
        if pts and x - pts[-1][0] < 1e-3:
            pts[-1] = [pts[-1][0], min(pts[-1][1], h)]
        else:
            pts.append([x, h])
    return [[round(x, 3), round(h, 1)] for x, h in pts]


def write_config(base_path, out_path, pts, case_dir):
    text = open(base_path).read()
    rp = "res_points = [" + ", ".join(f"[{x:g}, {h:g}]" for x, h in pts) + "]   # sweep_refined.py: the margin band"
    text, n = re.subn(r"^res_points\s*=.*$", lambda m: rp, text, count=1, flags=re.M)
    if n != 1:
        raise SystemExit(f"{base_path}: no res_points line")
    cd = f'case_dir = "{case_dir}"                # sweep_refined.py: this segment\'s mesh'
    text, n = re.subn(r"^case_dir\s*=.*$", lambda m: cd, text, count=1, flags=re.M)
    if n != 1:
        text, n = re.subn(r"^\[paths\]\s*$", lambda m: "[paths]\n" + cd, text, count=1, flags=re.M)
        if n != 1:
            raise SystemExit(f"{base_path}: no [paths] section")
    with open(out_path, "w") as f:
        f.write(f"# generated by jobs/sweep_refined.py from {os.path.relpath(base_path, ROOT)}\n" + text)


def converged(folder):
    """the converged (d km, state path) of a sweep folder, in order"""
    f = os.path.join(folder, "sweep.csv")
    if not os.path.exists(f):
        return []
    rows = list(csv.DictReader(open(f)))
    return [(float(r["d_km"]), os.path.join(folder, "points", f"state_{int(round(float(r['d_km']) * 10)):05d}.npz"))
            for r in rows if str(r.get("converged")) == "1"]


def last_converged(folder):
    c = converged(folder)
    return (c[-1] if c else None), c


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("config")
    ap.add_argument("--from-sweep")
    ap.add_argument("--from-state")
    ap.add_argument("--d-km", type=float)
    ap.add_argument("--d-end-km", type=float, default=0.0)
    ap.add_argument("--span-km", type=float, default=50.0)
    ap.add_argument("--pad-km", type=float, default=10.0)
    ap.add_argument("--grade-km", type=float, default=10.0)
    ap.add_argument("--fine", type=float, default=250.0)
    ap.add_argument("--step-frac", type=float, default=0.2)
    ap.add_argument("--step-min-km", type=float, default=1.0)
    ap.add_argument("--step-max-km", type=float, default=25.0)
    ap.add_argument("--gl-rounds", type=int, default=6)
    ap.add_argument("--maxit", type=int)
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--predictor", choices=["none", "secant"], default="none",
                    help="secant: each Newton from the linear extrapolation of the last two converged points (the "
                         "point before a segment's start carried over onto its mesh)")
    ap.add_argument("--prev-state", help="with --from-state: the converged point before it (the secant's second "
                                         "point for the first new point)")
    ap.add_argument("--out-root", default="sweep_refined",
                    help="the segments' folder under the work dir (another name: a branch run beside the main sweep)")
    ap.add_argument("--tag-prefix", default="m",
                    help="the segments' tag prefix (configs <work>/refined/<tag>.toml, meshes <work>/<tag>/): another "
                         "prefix keeps a branch's meshes apart from the main sweep's")
    ap.add_argument("--shelf-break", default="--strip-divide-r-km 1520.8 --r-break-km 450 --factor 30 --width-km 10",
                    help="jobs/shelf_break.py's arguments (as jobs/flowline_coarse_newton.cmd)")
    a = ap.parse_args()
    cfg = load_config(a.config)
    work = cfg["_work"]
    c = cfg["case"]
    base = c["res_points"]
    front_km = float(c.get("front_km", base[-1][0]))
    prev = None                                  # the converged point before src (the secant's second point)
    if a.from_sweep:
        got, allc = last_converged(a.from_sweep)
        if got is None:
            raise SystemExit(f"{a.from_sweep}: no converged row in sweep.csv")
        d0, src = got
        prev = allc[-2][1] if len(allc) > 1 else None
    else:
        if not (a.from_state and a.d_km is not None):
            raise SystemExit("give --from-sweep DIR, or --from-state STATE.npz with --d-km D")
        d0, src = a.d_km, a.from_state
        prev = a.prev_state
    os.makedirs(os.path.join(work, "refined"), exist_ok=True)
    seg_root = os.path.join(work, a.out_root)
    os.makedirs(seg_root, exist_ok=True)
    py = sys.executable
    while d0 > a.d_end_km + 1e-6:
        s = load_state(src)
        xgl = gl_position(s.frozen, s.diag) / 1e3
        h0 = xgl - d0
        tag = f"{a.tag_prefix}{int(round(h0)):04d}"
        d1 = max(d0 - a.span_km, a.d_end_km)
        seg = os.path.join(seg_root, f"seg_{tag}")
        got, allc = last_converged(seg)
        if got is not None and abs(got[0] - d1) < 1e-6:
            log(f"segment {tag} (d {d0:g} -> {d1:g} km) done already")
            prev = allc[-2][1] if len(allc) > 1 else src
            d0, src = got
            continue
        pts = banded_points(base, h0 - a.pad_km, h0 + (d0 - d1) + a.pad_km, a.fine, a.grade_km, front_km)
        log(f"segment {tag}: from {os.path.relpath(src, ROOT)} (d {d0:g} km, grounding line {xgl:.2f} km, head "
            f"{h0:.2f} km) to d {d1:g} km (head {xgl - d1:.2f} km); band {a.fine:g} m over {h0 - a.pad_km:.1f} .. "
            f"{h0 + d0 - d1 + a.pad_km:.1f} km; res_points {pts}")
        cfgf = os.path.join(work, "refined", f"{tag}.toml")
        mdir = os.path.join(work, tag)
        if a.dry_run:
            d0, src = d1, src            # (the segments' meshes only: the next head assumed at h0 + span)
            continue
        write_config(a.config, cfgf, pts, "{work}/" + tag)
        st0, st1, st2 = (os.path.join(mdir, f) for f in ("state0.npz", "start0.npz", "start.npz"))
        if not os.path.exists(st0):
            run([py, "-u", "-m", "ess", "setup", cfgf])
            run([py, "-u", "-m", "ess", "init", cfgf, "--out", st0])
        if not os.path.exists(st1):
            run([py, "-u", "-m", "ess", "transfer", cfgf, "--state", st0, "--from", src, "--out", st1])
        if not os.path.exists(st2):
            run([py, "jobs/shelf_break.py", st1, st2] + a.shelf_break.split() + ["--force"])
        cmd = [py, "-u", "-m", "ess", "sweep", cfgf, "--state", st2, "--d-start-km", f"{d0:g}", "--d-end-km",
               f"{d1:g}", "--step-frac", f"{a.step_frac:g}", "--step-min-km", f"{a.step_min_km:g}", "--step-max-km",
               f"{a.step_max_km:g}", "--gl-rounds", str(a.gl_rounds), "--out", seg]
        if a.maxit:
            cmd += ["--maxit", str(a.maxit)]
        if a.predictor == "secant":
            cmd += ["--predictor", "secant"] + (["--prev-state", prev] if prev else [])
        run(cmd)
        got, allc = last_converged(seg)
        if got is None or abs(got[0] - d1) > 1e-6:
            log(f"segment {tag} stopped before its end (last converged d {got[0] if got else 'none'} km): stopping")
            sys.exit(1)
        prev = allc[-2][1] if len(allc) > 1 else src
        d0, src = got
    log(f"done: d {a.d_end_km:g} km reached")


if __name__ == "__main__":
    main()
